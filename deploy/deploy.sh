#!/usr/bin/env bash
# DEPLOY SCRIPT - runs ON the EC2 server (as root, started by AWS Systems Manager).
#
#     bash deploy.sh <s3-bucket>
#
#  1. Reads s3://<bucket>/latest.txt to find the latest successful build
#  2. Downloads that build zip from S3 and unpacks it as a new release folder
#  3. Installs the Python dependencies into the shared virtual environment
#  4. Points /opt/authapp/current at the new release and restarts the service
#  5. Calls /health until the NEW build answers; if it never does, rolls back
#
# The database lives in /opt/authapp/data (outside the release folders), so a
# deployment never touches your users and companies.
set -euo pipefail

BUCKET="${1:?usage: deploy.sh <s3-bucket>}"

# Overridable so the script can also be tested away from a real server
APP_ROOT="${APP_ROOT:-/opt/authapp}"
AWS_BIN="${AWS_BIN:-/usr/local/bin/aws}"
PYTHON_BIN="${PYTHON_BIN:-python3}"
SERVICE="${SERVICE:-authapp}"
HEALTH_URL="${HEALTH_URL:-http://127.0.0.1/health}"
HEALTH_RETRIES="${HEALTH_RETRIES:-20}"
KEEP_RELEASES="${KEEP_RELEASES:-5}"

log() { echo "[deploy] $*"; }

mkdir -p "$APP_ROOT/releases" "$APP_ROOT/data" "$APP_ROOT/tmp"
WORK="$(mktemp -d "$APP_ROOT/tmp/deploy.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

# ---- 1. find the latest successful build ------------------------------------
log "Looking up the latest build in s3://$BUCKET/latest.txt"
KEY="$("$AWS_BIN" s3 cp "s3://$BUCKET/latest.txt" - | tr -d '[:space:]')"
if [ -z "$KEY" ]; then
  log "ERROR: latest.txt is empty"
  exit 1
fi
log "Latest build: $KEY"

# ---- 2. download and unpack it as a new release -----------------------------
"$AWS_BIN" s3 cp "s3://$BUCKET/$KEY" "$WORK/build.zip" --only-show-errors
RELEASE_NAME="$(basename "$KEY" .zip)"
RELEASE_DIR="$APP_ROOT/releases/$RELEASE_NAME"
rm -rf "$RELEASE_DIR"
mkdir -p "$RELEASE_DIR"
unzip -q "$WORK/build.zip" -d "$RELEASE_DIR"
chmod -R a+rX "$RELEASE_DIR"
BUILD_ID="$(tr -d '[:space:]' < "$RELEASE_DIR/BUILD_ID")"
VERSION="$(tr -d '[:space:]' < "$RELEASE_DIR/VERSION")"
log "Unpacked version $VERSION (build $BUILD_ID) into $RELEASE_DIR"

# ---- 3. dependencies --------------------------------------------------------
if [ ! -x "$APP_ROOT/venv/bin/python" ]; then
  log "Creating the virtual environment"
  "$PYTHON_BIN" -m venv "$APP_ROOT/venv"
fi
log "Installing dependencies"
"$APP_ROOT/venv/bin/pip" install --quiet --disable-pip-version-check -r "$RELEASE_DIR/requirements.txt"

# ---- 4. switch to the new release and restart -------------------------------
PREVIOUS=""
if [ -L "$APP_ROOT/current" ]; then
  PREVIOUS="$(readlink -f "$APP_ROOT/current")"
fi
ln -sfn "$RELEASE_DIR" "$APP_ROOT/current"
log "Restarting the $SERVICE service"
systemctl restart "$SERVICE"

# ---- 5. wait until the NEW build answers on /health -------------------------
healthy() {
  local expected="$1" body
  for _ in $(seq 1 "$HEALTH_RETRIES"); do
    body="$(curl -fsS --max-time 5 "$HEALTH_URL" 2>/dev/null || true)"
    if echo "$body" | grep -Eq "\"build\" *: *\"$expected\""; then
      return 0
    fi
    sleep 2
  done
  return 1
}

if healthy "$BUILD_ID"; then
  log "SUCCESS: version $VERSION (build $BUILD_ID) is live"
else
  log "ERROR: the new build did not become healthy"
  journalctl -u "$SERVICE" -n 30 --no-pager || true
  if [ -n "$PREVIOUS" ] && [ -f "$PREVIOUS/BUILD_ID" ]; then
    log "Rolling back to $(basename "$PREVIOUS")"
    ln -sfn "$PREVIOUS" "$APP_ROOT/current"
    systemctl restart "$SERVICE"
    if healthy "$(tr -d '[:space:]' < "$PREVIOUS/BUILD_ID")"; then
      log "Rollback succeeded: the previous build is serving again"
    else
      log "Rollback FAILED: check the service logs on the server"
    fi
  fi
  exit 1
fi

# ---- 6. tidy up: keep only the newest releases ------------------------------
CURRENT_REAL="$(readlink -f "$APP_ROOT/current")"
# Release folder names are generated by the build (build-VERSION-RUN-SHA), so ls is safe here
# shellcheck disable=SC2012
mapfile -t OLD < <(ls -1dt "$APP_ROOT"/releases/*/ | tail -n +"$((KEEP_RELEASES + 1))")
for dir in "${OLD[@]:-}"; do
  dir="${dir%/}"
  [ -n "$dir" ] || continue
  [ "$(readlink -f "$dir")" = "$CURRENT_REAL" ] && continue
  log "Removing old release $(basename "$dir")"
  rm -rf "$dir"
done
